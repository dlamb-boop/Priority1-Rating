BY_CODE = {code: (code, description, group) for code, description, group in ACCESSORIALS}


def accessorial_label(code: str) -> str:
    row = BY_CODE.get(code.strip().upper())
    return row[1] if row else code


def option_label(code: str) -> str:
    return f"{code} — {accessorial_label(code)}"


def code_from_label(label: str) -> str:
    return label.split("—", 1)[0].strip().upper()
